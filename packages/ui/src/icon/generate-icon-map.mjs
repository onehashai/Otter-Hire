#!/usr/bin/env node
/**
 * Generates icon-map.tsx with only these icons so the bundle stays small.
 * Run: npm run generate:icons
 */
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "icon-map.tsx");

const names = [
  "ArrowLeft",
  "Bold",
  "Briefcase",
  "Building2",
  "Check",
  "ChevronLeft",
  "CircleAlert",
  "Clock",
  "Code",
  "Crown",
  "DollarSign",
  "Eye",
  "EyeOff",
  "Filter",
  "Heading1",
  "Heading2",
  "Heading3",
  "Italic",
  "Link",
  "List",
  "ListOrdered",
  "Loader",
  "Mail",
  "MapPin",
  "Mic",
  "MoreHorizontal",
  "PenLine",
  "Plus",
  "ScrollText",
  "Search",
  "Send",
  "Shield",
  "ShieldCheck",
  "Sparkles",
  "Underline",
  "Upload",
  "UserCheck",
  "UserPlus",
  "Users",
  "X",
];

const imports = names.join(",\n  ");
const mapEntries = names.map((n) => `  ${n},`).join("\n");

const out = `/**
 * Generated by generate-icon-map.mjs - do not edit by hand.
 * Run: npm run generate:icons
 */
import {
  ${imports},
} from "lucide-react";

const icons = {
${mapEntries}
} as const;

export type IconName = keyof typeof icons;
export const iconMap = icons;
`;

writeFileSync(outPath, out);
console.log("Generated", outPath, "with", names.length, "icons.");
